"""Writes the migration that seeds the informational translations of the current legal texts.

Source: tables/legal/tr.json (the Turkish texts in force: kind -> {title, body}) and tables/legal/<lang>.py
(LEGAL = {kind: (title, body)}). A translation is attached to whichever legal_documents row has exactly that Turkish
body (md5), so the same migration works on every database whatever the version numbers are, and a text that has
changed since gets no stale translation (docs/ARCHITECTURE.md §11, Hukuki metin çevirileri).

Usage: python tool/l10n/legal_write.py <migration file>
"""
import hashlib
import importlib.util
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
TABLES = HERE / 'tables' / 'legal'
LANGUAGES = ['en', 'de', 'fr', 'nl', 'es', 'pt', 'it', 'ru', 'ar', 'az', 'uk']
QUOTE = '$legal$'


def load(lang):
    spec = importlib.util.spec_from_file_location(f'legal_{lang}', TABLES / f'{lang}.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.LEGAL


def blocks(text):
    return [b for b in text.split('\n\n') if b.strip()]


def quoted(text):
    assert QUOTE not in text
    return f'{QUOTE}{text}{QUOTE}'


def main(out):
    turkish = json.loads((TABLES / 'tr.json').read_text(encoding='utf-8'))
    rows = []
    problems = []
    for lang in LANGUAGES:
        legal = load(lang)
        if set(legal) != set(turkish):
            problems.append(f'{lang}: kinds {sorted(set(legal) ^ set(turkish))}')
        for kind, source in turkish.items():
            if kind not in legal:
                continue
            title, body = legal[kind]
            if len(blocks(body)) != len(blocks(source['body'])):
                problems.append(f'{lang}/{kind}: {len(blocks(body))} paragraphs, Turkish has {len(blocks(source["body"]))}')
            if body.count('\n') != source['body'].count('\n'):
                problems.append(f'{lang}/{kind}: {body.count(chr(10))} lines, Turkish has {source["body"].count(chr(10))}')
            digest = hashlib.md5(source['body'].encode('utf-8')).hexdigest()
            rows.append(f"  ('{kind}', '{digest}', '{lang}', {quoted(title)}, {quoted(body)})")
    if problems:
        sys.exit('\n'.join(problems))
    sql = (
        '-- Faz 19g: informational translations of the legal texts in force (docs/ARCHITECTURE.md §11).\n'
        '-- Generated by app/tool/l10n/legal_write.py; edit tables/legal/*, not this file.\n'
        '-- Each translation joins the legal_documents row whose Turkish body has the same md5, so it lands on the\n'
        '-- right version everywhere and never on a text that has changed since. The Turkish text stays binding.\n'
        'insert into public.legal_document_translations (kind, version, language, title, body)\n'
        'select d.kind, d.version, v.language, v.title, v.body\n'
        'from public.legal_documents d\n'
        'join (values\n'
        + ',\n'.join(rows)
        + '\n) as v(kind, tr_md5, language, title, body)\n'
        '  on d.kind = v.kind and md5(d.body) = v.tr_md5\n'
        'on conflict (kind, version, language) do nothing;\n'
    )
    pathlib.Path(out).write_text(sql, encoding='utf-8', newline='\n')
    print(f'{len(rows)} translations -> {out}')


if __name__ == '__main__':
    main(sys.argv[1])
