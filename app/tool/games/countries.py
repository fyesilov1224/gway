"""Writes the country names for the chess flag picker in the 12 app languages from Unicode CLDR (pip install babel).

Usage: python tool/games/countries.py
Output: packages/features/games/lib/src/domain/countries.dart (checked in). Codes are ISO 3166-1 alpha-2 with a flag
in flag-icons; names follow each language's CLDR short form where one exists.
"""
import pathlib
from babel import Locale

LANGS = ['tr', 'en', 'de', 'fr', 'nl', 'es', 'pt', 'it', 'ru', 'ar', 'az', 'uk']
# CLDR region codes that are not countries with a flag of their own.
SKIP = {'EU', 'EZ', 'UN', 'ZZ', 'QO', 'AC', 'CP', 'DG', 'EA', 'IC', 'TA', 'XA', 'XB', 'CQ'}

en = Locale('en').territories
codes = sorted(c for c in en if len(c) == 2 and c.isalpha() and c not in SKIP)

out = pathlib.Path(__file__).resolve().parents[2] / 'packages/features/games/lib/src/domain/countries.dart'
lines = [
    '// Generated by tool/games/countries.py from Unicode CLDR. Do not edit by hand.',
    '',
    '/// ISO 3166-1 alpha-2 codes offered in the flag picker.',
    'const countryCodes = [',
]
lines += [f"  '{c}'," for c in codes]
lines += ['];', '', '/// Country names by language, in [countryCodes] order.', 'const countryNames = <String, List<String>>{']
for lang in LANGS:
    names = Locale.parse('pt_BR' if lang == 'pt' else lang).territories
    lines.append(f"  '{lang}': [")
    for c in codes:
        name = names.get(c) or en[c]
        lines.append("    '" + name.replace('\\', '\\\\').replace("'", "\\'") + "',")
    lines.append('  ],')
lines += ['};', '']
out.write_text('\n'.join(lines), encoding='utf-8')
print(len(codes), 'countries x', len(LANGS), 'languages ->', out)
