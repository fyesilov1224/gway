create function private.notify_mind_challenge()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if private.wants_notification(new.opponent_id, 'mind_challenge') then
    insert into public.notifications (recipient_id, actor_id, type) values (new.opponent_id, new.challenger_id, 'mind_challenge');
  end if;
  return null;
end;
$$;

revoke all on function private.notify_mind_challenge() from public;

create trigger notify_mind_challenge after insert on public.mind_challenges
  for each row execute function private.notify_mind_challenge();
