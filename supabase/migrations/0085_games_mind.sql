  using (
    a_id = (select auth.uid()) or b_id = (select auth.uid())
    or (select private.is_platform_staff())
    or ((a_id is null or private.is_account_visible(a_id)) and (b_id is null or private.is_account_visible(b_id)))
  );

create policy mind_seeks_select_own on public.mind_seeks for select to authenticated
  using (user_id = (select auth.uid()));

create policy mind_challenges_select_party on public.mind_challenges for select to authenticated
  using (challenger_id = (select auth.uid()) or opponent_id = (select auth.uid()) or (select private.is_platform_staff()));

