-- 0085_games_mind
-- Faz 21a (docs/ARCHITECTURE.md §3j): Zihin Düellosu, a live duel of mixed questions (math, attention, memory, reflex)
-- in 5, 10, 20 or 50 questions. The API (C#) generates the questions, serves them one at a time, scores the answers
-- and updates Elo; clients read matches under RLS and follow both scores through Realtime. Questions and answers are
-- never readable by clients. The flag and a platform suspension come from chess_players, the games player card.
-- owner: games

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------
create table public.mind_ratings (
  user_id    uuid not null references public.profiles (id) on delete cascade,
  length     int not null check (length in (5, 10, 20, 50)),
  rating     int not null default 1200 check (rating >= 100),
  peak       int not null default 1200,
  games      int not null default 0 check (games >= 0),
  wins       int not null default 0 check (wins >= 0),
  draws      int not null default 0 check (draws >= 0),
  losses     int not null default 0 check (losses >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, length)
);

comment on table public.mind_ratings is 'owner: games. Elo per question count; written by the API with the match result.';

create index mind_ratings_board_idx on public.mind_ratings (length, rating desc);

create table public.mind_matches (
  id          uuid primary key default gen_random_uuid(),
  a_id        uuid references public.profiles (id) on delete set null,
  b_id        uuid references public.profiles (id) on delete set null,
  length      int not null check (length in (5, 10, 20, 50)),
  rated       boolean not null,
  source      text not null check (source in ('seek', 'challenge')),
  status      text not null default 'active' check (status in ('active', 'finished', 'aborted')),
  result      text check (result in ('a', 'b', 'draw')),
  termination text check (termination in ('completed', 'time', 'resign', 'aborted')),
  -- Points per answered question, in order; the score is their sum. Answers themselves stay in mind_answers.
  a_points    int[] not null default '{}',
  b_points    int[] not null default '{}',
  a_score     int not null default 0,
  b_score     int not null default 0,
  -- Took their first question: the 30-second window after the start is met.
  a_joined    boolean not null default false,
  b_joined    boolean not null default false,
  a_rating    int not null,
  b_rating    int not null,
  a_delta     int,
  b_delta     int,
  starts_at   timestamptz not null,
  deadline_at timestamptz not null,
  rematch_of  uuid references public.mind_matches (id) on delete set null,
  created_at  timestamptz not null default now(),
  ended_at    timestamptz,
  constraint mind_matches_players check (a_id <> b_id),
  constraint mind_matches_progress check (cardinality(a_points) <= length and cardinality(b_points) <= length),
  constraint mind_matches_window check (deadline_at > starts_at),
  constraint mind_matches_outcome check (
    (status = 'active' and result is null and termination is null and ended_at is null)
    or (status = 'finished' and result is not null and termination is not null and termination <> 'aborted' and ended_at is not null)
    or (status = 'aborted' and result is null and termination = 'aborted' and ended_at is not null))
);

comment on table public.mind_matches is
  'owner: games. One duel. Only the API writes: it scores every answer with server time. Realtime-published.';

create index mind_matches_a_idx on public.mind_matches (a_id, created_at desc);
create index mind_matches_b_idx on public.mind_matches (b_id, created_at desc);
create index mind_matches_active_idx on public.mind_matches (deadline_at) where status = 'active';

-- The questions of a match with their solutions: the API only.
create table public.mind_questions (
  match_id uuid not null references public.mind_matches (id) on delete cascade,
  idx      int not null check (idx >= 0),
  kind     text not null check (kind in ('math', 'attention', 'memory', 'reflex')),
  level    int not null check (level between 1 and 4),
  payload  jsonb not null,
  solution jsonb not null,
  limit_ms int not null check (limit_ms > 0),
  primary key (match_id, idx)
);

comment on table public.mind_questions is 'owner: games. Generated by the API when the match opens; never readable by clients.';

-- When each player was served each question and what they answered: the API only.
create table public.mind_answers (
  match_id    uuid not null references public.mind_matches (id) on delete cascade,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  idx         int not null,
  served_at   timestamptz not null default now(),
  answered_at timestamptz,
  answer      jsonb,
  elapsed_ms  int,
  points      int,
  correct     boolean,
  primary key (match_id, user_id, idx),
  foreign key (match_id, idx) references public.mind_questions (match_id, idx) on delete cascade
);

comment on table public.mind_answers is 'owner: games. Served and answered questions with server times; never readable by clients.';

create table public.mind_seeks (
  user_id    uuid primary key references public.profiles (id) on delete cascade,
  length     int not null check (length in (5, 10, 20, 50)),
  rating     int not null,
  match_id   uuid references public.mind_matches (id) on delete cascade,
  created_at timestamptz not null default now(),
  touched_at timestamptz not null default now()
);

comment on table public.mind_seeks is
  'owner: games. Someone waiting for a quick duel; match_id is set when paired. Refreshed every 20 s, dropped after 60 s.';

create index mind_seeks_pool_idx on public.mind_seeks (length, created_at) where match_id is null;

create table public.mind_challenges (
  id            uuid primary key default gen_random_uuid(),
  challenger_id uuid not null references public.profiles (id) on delete cascade,
  opponent_id   uuid not null references public.profiles (id) on delete cascade,
  length        int not null check (length in (5, 10, 20, 50)),
  rated         boolean not null,
  status        text not null default 'pending' check (status in ('pending', 'accepted', 'declined', 'canceled', 'expired')),
  match_id      uuid references public.mind_matches (id) on delete set null,
  rematch_of    uuid references public.mind_matches (id) on delete set null,
  created_at    timestamptz not null default now(),
  expires_at    timestamptz not null default now() + interval '10 minutes',
  responded_at  timestamptz,
  constraint mind_challenges_people check (challenger_id <> opponent_id)
);

comment on table public.mind_challenges is
  'owner: games. An invitation to a duel; pending for 10 minutes. Both people read it; the API writes.';

create unique index mind_challenges_one_pending on public.mind_challenges (challenger_id, opponent_id) where status = 'pending';
create index mind_challenges_opponent_idx on public.mind_challenges (opponent_id, created_at desc);
create index mind_challenges_challenger_idx on public.mind_challenges (challenger_id, created_at desc);
create index mind_challenges_pending_idx on public.mind_challenges (expires_at) where status = 'pending';

